/**
 * GENERIC_FOOTAGE_FALLBACK — moving, rights-clear footage for a sentence nothing else could picture.
 *
 * ── Where it sits ───────────────────────────────────────────────────────────────────────────────
 *
 * The last MOVING rung, under every source that could be specific to the sentence:
 *
 *   1  YouTube → own archive → open sources → stock       the sourcing ladder (sourcingTiers.ts)
 *   2  a data graphic or a map                             the sentence's own facts as its picture
 *   3  a generated video or still                          GENERATED_VIDEO/IMAGE_FALLBACK
 *   4  GENERIC FOOTAGE                                     this module — logged GENERIC_FOOTAGE_FALLBACK
 *   5  a drawn chapter card                                CHAPTER_CARD_FALLBACK — never delivered as cover
 *
 * Video 650 is why rung 4 exists: a film in which every sentence had footage except the ones that
 * fell through to a card, and a card is refused at delivery (deliveryGate: CHAPTER_CARD_PLACEHOLDER).
 * The rule the brief sets is that every spoken sentence ends under VALID MOVING COVERAGE or with an
 * explicit error — so the floor under the ladder has to move, decode, cover the sentence's seconds,
 * be free of rights questions and be available on every worker. Two sources, in order:
 *
 *   archive    an active video asset in the media archive tagged `generic` (an operator's own library
 *              of rights-clear, non-specific moving footage — skies, water, traffic, textures), chosen
 *              for its length and rotated so one film does not repeat one clip;
 *   synthetic  a slow-moving colour field this process renders with ffmpeg's own `gradients` source
 *              (plus a little grain): no rights, no network, decodable by construction, any length.
 *
 * What a generic clip is NOT: a picture that fits the sentence. It carries `contentApproval:
 * "generic_footage"` rather than the picture editor's `judge_fit`, the coverage check counts it as
 * cover of kind `generic_footage` (sentenceCoverage.ts), and every log line names it, so a film
 * delivered on generic footage can be read as such — this is visual coverage, not content fit.
 */
import { execFile } from "child_process";
import * as fs from "fs";

export const GENERIC_FOOTAGE_FALLBACK = "GENERIC_FOOTAGE_FALLBACK";

/** The provider name a generic ARCHIVE clip (real, rights-clear footage) carries through the lineage, the archive and the timeline. */
export const GENERIC_FOOTAGE_PROVIDER = "generic_footage";

/**
 * PRE-DEPLOY CHECK — the synthetic colour field is NOT footage. It is the emergency floor for a
 * sentence that no real generic clip could cover either, and it carries its own provider name so
 * the coverage check, the delivery gate, the archive and every log line can name it as what it is:
 * a placeholder that is NOT cover (its sentence stays uncovered, the delivery gate refuses the film)
 * and is named as a QUALITY PROBLEM, never a successful picture choice. Real generic
 * footage is what an operator puts in the archive under the `generic` tag (see
 * docs/generic-footage.md): a small, rights-clear set, present on every worker through the archive.
 */
export const SYNTHETIC_PLACEHOLDER_PROVIDER = "synthetic_placeholder";
export const SYNTHETIC_PLACEHOLDER_TITLE = "EMERGENCY PLACEHOLDER — synthetic colour field (not footage)";
export const SYNTHETIC_PLACEHOLDER_LICENSE = "Generated by FastVid — emergency placeholder, no third-party rights, NOT footage";

/** The archive tag an operator puts on rights-clear, non-specific moving footage. */
export const GENERIC_ARCHIVE_TAG = "generic";

/** Where this system's own generated generic clips are filed (stockArchive.ts: `generic`). */
export const GENERIC_ARCHIVE_SLUG = "generic";

/** How long a film may spend on this rung before the render needs the time for itself. */
export const GENERIC_FOOTAGE_RESERVE_MS = 2 * 60_000;

/** The archive's own floor for a video (archiveIngestion.ts MIN_VIDEO_DURATION_SEC) plus a margin. */
export const SYNTHETIC_MIN_SEC = 3.5;

export type GenericFootageSource = "archive" | "synthetic";

export type GenericFootageDecision = { place: true } | { place: false; reason: string };

/** Whether a sentence still without a picture gets generic footage. Every "no" names its reason. */
export function genericFootageDecision(input: {
  /** The sentence already has a picture of any kind (an approved clip, a generated one, a graphic). */
  hasPicture: boolean;
  /** Milliseconds the render has left, or null when nothing is keeping time. */
  remainingMs: number | null;
  reserveMs?: number;
}): GenericFootageDecision {
  if (input.hasPicture) return { place: false, reason: "the sentence already has a picture" };
  const reserve = input.reserveMs ?? GENERIC_FOOTAGE_RESERVE_MS;
  if (input.remainingMs != null && input.remainingMs < reserve) {
    return { place: false, reason: `${Math.round(input.remainingMs / 1000)}s left in the render, under the ${Math.round(reserve / 1000)}s reserve` };
  }
  return { place: true };
}

export type GenericArchiveCandidate = {
  id: number;
  mediaType: string;
  mediaStatus?: string | null;
  isActive?: number | null;
  durationSec?: number | null;
};

/**
 * The archive clip for a sentence: active, a video, READY (or from before the status existed),
 * long enough to cover the sentence without being held past its source, not yet used in this
 * film when another qualifies, and rotated by `seed` so two films do not open on the same clip.
 */
export function pickGenericArchiveAsset<T extends GenericArchiveCandidate>(
  assets: readonly T[],
  opts: { neededSec: number; usedIds: ReadonlySet<number>; seed: number }
): T | null {
  const usable = assets.filter(
    (a) =>
      a.mediaType === "video" &&
      (a.isActive == null || a.isActive === 1) &&
      (a.mediaStatus == null || a.mediaStatus === "READY") &&
      (a.durationSec ?? 0) >= opts.neededSec
  );
  if (usable.length === 0) return null;
  const fresh = usable.filter((a) => !opts.usedIds.has(a.id));
  const pool = fresh.length > 0 ? fresh : usable;
  const sorted = [...pool].sort((a, b) => a.id - b.id);
  return sorted[Math.abs(Math.trunc(opts.seed)) % sorted.length] ?? null;
}

/** Six palettes of three colours: muted, cinematic, never a flat blue-grey card. */
export const SYNTHETIC_PALETTES: ReadonlyArray<readonly [string, string, string]> = [
  ["#1b2a41", "#324a5f", "#0c1821"],
  ["#2f2a1f", "#5c4b2a", "#1a1712"],
  ["#1f3a2e", "#2e5d4b", "#0f1f18"],
  ["#3a1f2a", "#5d2e45", "#1f0f18"],
  ["#2a2f3a", "#4b5566", "#15181f"],
  ["#3a2e1f", "#66512e", "#1f1810"],
];

export function syntheticPaletteIndex(seed: number): number {
  return Math.abs(Math.trunc(seed)) % SYNTHETIC_PALETTES.length;
}

/** A stable provider id, so the archive can recognise the same generated clip again. */
export function syntheticAssetId(seed: number, durationSec: number): string {
  return `synthetic-p${syntheticPaletteIndex(seed)}-${Math.ceil(durationSec)}s`;
}

/**
 * ffmpeg arguments for the synthetic clip: a slowly rotating three-colour gradient field with a
 * little temporal grain, at the timeline's size and frame rate, stated on the encode (`-r`) as every
 * encode in this pipeline is since VIDEO 650. Motion is in the picture itself, not a camera move on a
 * still — `gradients` redraws every frame.
 */
export function syntheticMotionClipArgs(params: {
  output: string;
  durationSec: number;
  widthPx: number;
  heightPx: number;
  fps: number;
  seed: number;
}): string[] {
  const [c0, c1, c2] = SYNTHETIC_PALETTES[syntheticPaletteIndex(params.seed)]!;
  const dur = Math.max(SYNTHETIC_MIN_SEC, params.durationSec).toFixed(2);
  const src =
    `gradients=s=${params.widthPx}x${params.heightPx}:c0=${c0}:c1=${c1}:c2=${c2}:nb_colors=3` +
    `:speed=0.03:seed=${Math.abs(Math.trunc(params.seed)) % 1000}:rate=${params.fps}:duration=${dur}`;
  return [
    "-y", "-hide_banner", "-loglevel", "error",
    "-f", "lavfi", "-i", src,
    "-vf", "noise=alls=8:allf=t,format=yuv420p",
    "-r", String(params.fps),
    "-t", dur,
    "-c:v", "libx264", "-preset", "veryfast", "-crf", "18", "-pix_fmt", "yuv420p",
    "-an", "-movflags", "+faststart",
    params.output,
  ];
}

function run(bin: string, args: string[], timeoutMs: number): Promise<{ code: number | null; stderr: string }> {
  return new Promise((resolve) => {
    execFile(bin, args, { timeout: timeoutMs, maxBuffer: 8 * 1024 * 1024 }, (err, _stdout, stderr) => {
      const raw: unknown = err ? (err as { code?: unknown }).code : 0;
      resolve({ code: typeof raw === "number" ? raw : err ? 1 : 0, stderr: String(stderr ?? "") });
    });
  });
}

/** Renders the synthetic clip. False (with the reason) when ffmpeg could not. */
export async function makeSyntheticMotionClip(
  ffmpegBin: string,
  params: Parameters<typeof syntheticMotionClipArgs>[0]
): Promise<{ ok: true } | { ok: false; reason: string }> {
  const r = await run(ffmpegBin, syntheticMotionClipArgs(params), 120_000);
  if (r.code !== 0) return { ok: false, reason: `ffmpeg exited ${r.code}: ${r.stderr.trim().slice(-200)}` };
  let size = 0;
  try { size = fs.statSync(params.output).size; } catch { /* missing */ }
  if (size < 1_000) return { ok: false, reason: `ffmpeg wrote ${size} bytes` };
  return { ok: true };
}

/**
 * Whether the picture MOVES — measured, on the first seconds of the file, with ffmpeg's own
 * freezedetect: a clip whose frames do not change for half a second is not moving coverage. A card
 * rendered to video, a still without a camera move and a stalled encode all fail here.
 */
export async function clipHasMotion(
  ffmpegBin: string,
  filePath: string,
  opts: { sampleSec?: number; timeoutMs?: number } = {}
): Promise<{ moving: boolean; detail: string }> {
  const sampleSec = opts.sampleSec ?? 6;
  const r = await run(
    ffmpegBin,
    ["-hide_banner", "-nostats", "-t", String(sampleSec), "-i", filePath, "-vf", "freezedetect=n=0.003:d=0.5", "-an", "-f", "null", "-"],
    opts.timeoutMs ?? 60_000
  );
  if (r.code !== 0) return { moving: false, detail: `freezedetect could not run (exit ${r.code})` };
  const freezes = (r.stderr.match(/freeze_start/g) ?? []).length;
  return { moving: freezes === 0, detail: freezes === 0 ? `no freeze in the first ${sampleSec}s` : `${freezes} frozen stretch(es) in the first ${sampleSec}s` };
}

/** One line per placement, read back by the log analyser and the report. No secrets, no paths outside the work dir. */
export function formatGenericFootagePlacement(p: {
  sceneIndex: number;
  beatIndex: number;
  source: GenericFootageSource;
  assetId: number | string;
  durationSec: number;
  neededSec: number;
}): string {
  if (p.source === "synthetic") {
    return (
      `[${GENERIC_FOOTAGE_FALLBACK}] s${p.sceneIndex}b${p.beatIndex} placed source=synthetic asset=${p.assetId} ` +
      `duration=${p.durationSec.toFixed(2)}s needed=${p.neededSec.toFixed(2)}s — EMERGENCY PLACEHOLDER (provider=${SYNTHETIC_PLACEHOLDER_PROVIDER}): ` +
      `a generated colour field, NOT footage, NOT a content choice, NOT cover; a QUALITY PROBLEM, delivered and named for the customer to replace (VIDEO 653) — ` +
      `put real rights-clear clips in the archive under the "${GENERIC_ARCHIVE_TAG}" tag`
    );
  }
  return (
    `[${GENERIC_FOOTAGE_FALLBACK}] s${p.sceneIndex}b${p.beatIndex} placed source=archive asset=${p.assetId} ` +
    `duration=${p.durationSec.toFixed(2)}s needed=${p.neededSec.toFixed(2)}s — moving, rights-clear generic footage from the archive; ` +
    `NOT a content fit (contentApproval=generic_footage)`
  );
}
